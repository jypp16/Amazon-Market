-- Paso 15: igualar solo el contexto de creación; no convierte tablas ni datos existentes.
SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;
DELIMITER $$
BEGIN NOT ATOMIC
 IF BINARY DATABASE() <> BINARY '__SPRINT3_DESTINO__'
    OR BINARY COALESCE(@SPRINT3_DESPLIEGUE_LOCAL_AUTORIZADO,'') <> BINARY 'amazon_market'
    OR BINARY COALESCE(@SPRINT3_BASE_CONFIRMADA,'') <> BINARY DATABASE()
    OR (DATABASE() <> 'amazon_market' AND DATABASE() NOT REGEXP '^amazon_market_sprint3_deploy_[A-Za-z0-9_]+$')
    OR COALESCE(@SPRINT3_VENTANA_MANTENIMIENTO,0) <> 1 THEN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='CONTEXTO_DESPLIEGUE_NO_AUTORIZADO';
 END IF;
 IF EXISTS(SELECT 1 FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='sprint3_migracion_control') THEN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='CONTEXTO_REQUIERE_BASE_PREVIA_SIN_CONTROL';
 END IF;
END$$
DELIMITER ;
SELECT DEFAULT_CHARACTER_SET_NAME AS charset_anterior,DEFAULT_COLLATION_NAME AS collation_anterior
 FROM information_schema.SCHEMATA WHERE SCHEMA_NAME=DATABASE();
ALTER DATABASE `__SPRINT3_DESTINO__` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
SELECT DEFAULT_CHARACTER_SET_NAME AS charset_nuevo,DEFAULT_COLLATION_NAME AS collation_nueva
 FROM information_schema.SCHEMATA WHERE SCHEMA_NAME=DATABASE();
